#!/usr/bin/env node
/**
 * Infer part-of-speech tags from English glosses in the bundled definition
 * dictionaries (Hopkins, 84000) for entries that carry no explicit POS.
 *
 * The bundled dictionaries ship `form\tpos\tlemma\tsense\tfreq` rows where the
 * pos column is usually empty. A few gloss patterns are reliable POS signals:
 *   - a first gloss beginning with "to <verb>"  -> VERB
 *   - explicit adj./n./v. markers              -> ADJ / NOUN / VERB
 *   - 84000 <person>, <place>, <text> markers  -> PROPN
 *
 * Only high-confidence signals are applied; anything ambiguous is left
 * untagged so the SOAS/ACTib corpus layers can still fill it in.
 *
 * Output: public/data/dialect_packs/botok_general/dictionary/words/gloss_pos_inferred.tsv
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const WORDS_DIR = path.join(
  ROOT,
  "public/data/dialect_packs/botok_general/dictionary/words"
);
const SOURCES = ["hopkins.tsv", "84000.tsv"];
const OUT = path.join(WORDS_DIR, "gloss_pos_inferred.tsv");

const VERB_TO = /^\s*to\s+[a-z'-]+/iu;
const ADJ_MARK = /\b(adj|adjective)\b\.?/iu;
const VERB_MARK = /\b(v\.|verb)\b\.?/iu;
const NOUN_MARK = /\b(n\.|noun)\b\.?/iu;
const PROPN_MARK = /<(person|place|text|deity|school)>/iu;

function inferPos(sense) {
  const text = (sense || "").trim();
  if (!text) return null;
  if (VERB_TO.test(text)) return "VERB";
  if (PROPN_MARK.test(text)) return "PROPN";
  if (ADJ_MARK.test(text)) return "ADJ";
  if (VERB_MARK.test(text)) return "VERB";
  if (NOUN_MARK.test(text)) return "NOUN";
  return null;
}

function normalizeForm(word) {
  return word.replace(/་/gu, "").trim();
}

function main() {
  const kept = new Map(); // normalized form -> { word, tags: Set, hasPlainGloss: bool }
  let scanned = 0;
  let inferred = 0;

  for (const file of SOURCES) {
    const filePath = path.join(WORDS_DIR, file);
    if (!fs.existsSync(filePath)) continue;

    for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
      const trimmed = line.replace(/^﻿/, "").trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const [form, pos, , sense] = trimmed.split("\t");
      if (!form) continue;
      scanned += 1;
      if (pos && pos.trim()) continue; // explicit POS already present

      const key = normalizeForm(form);
      if (!kept.has(key)) {
        kept.set(key, { word: form.trim(), tags: new Set(), hasPlainGloss: false });
      }
      const record = kept.get(key);

      // A gloss without a <person>/<place>/... marker means the form is
      // defined as a common word somewhere; in that case a name-marked
      // sense elsewhere must not label the whole word a proper noun.
      if (sense && sense.trim() && !PROPN_MARK.test(sense)) {
        record.hasPlainGloss = true;
      }

      const tag = inferPos(sense);
      if (!tag) continue;
      inferred += 1;
      record.tags.add(tag);
    }
  }

  for (const record of kept.values()) {
    if (record.hasPlainGloss) {
      record.tags.delete("PROPN");
    }
  }

  const header = [
    "# POS tags inferred from English gloss patterns in the bundled dictionaries",
    "# (Hopkins, 84000). Generated by tools/build-gloss-pos.js — do not edit.",
    "# POS fallback layer — no definitions; used only to fill in missing",
    "#       part-of-speech tags.",
    "# form\tpos\tlemma\tsense\tfreq"
  ];

  const body = [];
  for (const { word, tags } of [...kept.values()].sort((a, b) =>
    a.word.localeCompare(b.word)
  )) {
    for (const tag of [...tags].sort()) {
      body.push(`${word}\t${tag}\t\t\t`);
    }
  }

  fs.writeFileSync(OUT, header.join("\n") + "\n" + body.join("\n") + "\n");
  console.log(
    `Scanned ${scanned} entries; inferred POS for ${inferred} ` +
      `(${kept.size} forms, ${body.length} rows) -> ${path.relative(ROOT, OUT)}`
  );
}

main();
